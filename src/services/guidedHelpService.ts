class SpeechGuidanceController {
  private currentUtterance: SpeechSynthesisUtterance | null = null;
  private isPaused = false;
  private isSpeaking = false;
  private availableVoices: SpeechSynthesisVoice[] = [];
  private listeners: Set<(speaking: boolean, paused: boolean) => void> = new Set();

  constructor() {
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      this.loadVoices();
      window.speechSynthesis.onvoiceschanged = () => {
        this.loadVoices();
      };
    }
  }

  private loadVoices() {
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      this.availableVoices = window.speechSynthesis.getVoices();
    }
  }

  public subscribe(listener: (speaking: boolean, paused: boolean) => void): () => void {
    this.listeners.add(listener);
    listener(this.isSpeaking, this.isPaused);
    return () => {
      this.listeners.delete(listener);
    };
  }

  private notify() {
    this.listeners.forEach((l) => l(this.isSpeaking, this.isPaused));
  }

  public isSupported(): boolean {
    return typeof window !== 'undefined' && 'speechSynthesis' in window && 'SpeechSynthesisUtterance' in window;
  }

  public isVoiceAvailableForLanguage(lang: LanguageCode): boolean {
    if (!this.isSupported()) return false;
    if (this.availableVoices.length === 0) {
      this.loadVoices();
    }
    const bcp47 = VOICE_LANG_MAP[lang] || 'en-IN';
    const langPrefix = bcp47.split('-')[0].toLowerCase();

    // Check if any installed voice matches the BCP47 code or prefix
    return this.availableVoices.some(
      (v) =>
        v.lang.toLowerCase() === bcp47.toLowerCase() ||
        v.lang.toLowerCase().replace('_', '-').startsWith(langPrefix)
    );
  }

  public speak(
    text: string,
    lang: LanguageCode,
    onStart?: () => void,
    onEnd?: () => void,
    onError?: (err: any) => void
  ): boolean {
    if (!this.isSupported()) {
      onError?.(new Error('SpeechSynthesis not supported'));
      return false;
    }

    // Cancel any existing speech
    this.stop();

    try {
      const utterance = new SpeechSynthesisUtterance(text);
      const bcp47 = VOICE_LANG_MAP[lang] || 'en-IN';
      utterance.lang = bcp47;
      utterance.rate = 0.95; // Friendly and accessible pace for clarity
      utterance.pitch = 1.0;

      // Find best matching voice
      if (this.availableVoices.length === 0) {
        this.loadVoices();
      }
      const langPrefix = bcp47.split('-')[0].toLowerCase();
      const matchedVoice = this.availableVoices.find(
        (v) =>
          v.lang.toLowerCase() === bcp47.toLowerCase() ||
          v.lang.toLowerCase().replace('_', '-').startsWith(langPrefix)
      );
      if (matchedVoice) {
        utterance.voice = matchedVoice;
      }

      utterance.onstart = () => {
        this.isSpeaking = true;
        this.isPaused = false;
        this.notify();
        onStart?.();
      };

      utterance.onend = () => {
        this.isSpeaking = false;
        this.isPaused = false;
        this.currentUtterance = null;
        this.notify();
        onEnd?.();
      };

      utterance.onerror = (e) => {
        // 'interrupted' or 'canceled' are intentional when users switch steps or close
        if (e.error !== 'interrupted' && e.error !== 'canceled') {
          console.warn('SpeechSynthesis error:', e);
        }
        this.isSpeaking = false;
        this.isPaused = false;
        this.currentUtterance = null;
        this.notify();
        onError?.(e);
      };

      utterance.onpause = () => {
        this.isPaused = true;
        this.notify();
      };

      utterance.onresume = () => {
        this.isPaused = false;
        this.notify();
      };

      this.currentUtterance = utterance;
      window.speechSynthesis.speak(utterance);
      return true;
    } catch (e) {
      console.warn('Failed to speak with SpeechSynthesis:', e);
      this.isSpeaking = false;
      this.isPaused = false;
      this.notify();
      onError?.(e);
      return false;
    }
  }

  public pause() {
    if (this.isSupported() && window.speechSynthesis.speaking && !window.speechSynthesis.paused) {
      window.speechSynthesis.pause();
      this.isPaused = true;
      this.notify();
    }
  }

  public resume() {
    if (this.isSupported() && window.speechSynthesis.paused) {
      window.speechSynthesis.resume();
      this.isPaused = false;
      this.notify();
    }
  }

  public stop() {
    if (this.isSupported()) {
      window.speechSynthesis.cancel();
    }
    this.isSpeaking = false;
    this.isPaused = false;
    this.currentUtterance = null;
    this.notify();
  }

  public getStatus() {
    return {
      isSpeaking: this.isSpeaking,
      isPaused: this.isPaused,
      isSupported: this.isSupported(),
    };
  }
}

export const speechController = new SpeechGuidanceController();
