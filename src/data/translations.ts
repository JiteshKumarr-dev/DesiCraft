export const createTranslator = (lang: LanguageCode): TranslateFn => {
  const currentTranslations = translations[lang] || translations.en;
  const dict = {
    ...(SITE_DICTIONARY[lang] || {}),
    ...(EXTRA_DICTIONARY[lang] || {}),
  };

  const translateCallable = (text: string): string => {
    if (!text || lang === 'en') return text;
    if (dict[text]) return dict[text];
    const trimmed = text.trim();
    if (dict[trimmed]) return dict[trimmed];
    return text;
  };

  return Object.assign(translateCallable, currentTranslations);
};

